prompt_components = sa.table(
    "prompt_components",
    sa.column("id", postgresql.UUID(as_uuid=True)),
    sa.column("name", sa.String),
    sa.column("description", sa.Text),
    sa.column("prompt_text", sa.Text),
    sa.column("updated_at", sa.DateTime(timezone=True)),
)

style_templates = sa.table(
    "style_templates",
    sa.column("id", postgresql.UUID(as_uuid=True)),
    sa.column("description", sa.Text),
    sa.column("updated_at", sa.DateTime(timezone=True)),
)


def _apply(versions: dict, template_desc: str) -> None:
    now = datetime.now(timezone.utc)
    for category, component_id in STYLE_COMPONENT_IDS.items():
        content = versions[category]
        op.execute(
            prompt_components.update()
            .where(prompt_components.c.id == component_id)
            .values(
                name=content["name"],
                description=content["description"],
                prompt_text=content["prompt_text"],
                updated_at=now,
            )
        )
    op.execute(
        style_templates.update()
        .where(style_templates.c.id == STYLE_TEMPLATE_ID)
        .values(description=template_desc, updated_at=now)
    )


def upgrade() -> None:
    """Rewrite the ensemble-theater style components to the topic-adaptive v2."""
    _apply(V2, TEMPLATE_DESC_V2)


def downgrade() -> None:
    """Restore the original v1 texts of the ensemble-theater style components."""
    _apply(V1, TEMPLATE_DESC_V1)
